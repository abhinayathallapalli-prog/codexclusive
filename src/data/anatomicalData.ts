import { DepartmentCode, LanguageCode } from '../types';

export interface AnatomicalRegion {
  id: string;
  name: Record<LanguageCode, string>;
  subtitle?: Record<LanguageCode, string>;
  category: 'head_neck' | 'torso' | 'upper_extremity' | 'lower_extremity' | 'systemic' | 'back';
  side?: 'left' | 'right' | 'bilateral' | 'midline';
  hasSubRegions: boolean;
  subRegionIds?: string[];
  svgCoordinates?: {
    cx?: number;
    cy?: number;
    r?: number;
    x?: number;
    y?: number;
    width?: number;
    height?: number;
    d?: string;
  };
  recommendedSymptoms?: string[];
}

export interface AnatomicalSubRegion {
  id: string;
  parentId: string;
  name: Record<LanguageCode, string>;
  hasSubRegions: boolean;
  childRegionIds?: string[];
  side?: 'left' | 'right' | 'bilateral' | 'midline';
  recommendedSymptoms?: string[];
}

export interface DetailedLocationOption {
  id: string;
  parentId: string;
  name: Record<LanguageCode, string>;
  side?: 'left' | 'right' | 'bilateral' | 'midline';
  recommendedSymptoms?: string[];
}

