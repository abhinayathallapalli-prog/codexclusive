export function getControlledBranchInfo(
  deptCode: DepartmentCode,
  branchCode?: string
): ControlledBranchMetadata {
  if (branchCode && CONTROLLED_BRANCHES_DATA[branchCode]) {
    return CONTROLLED_BRANCHES_DATA[branchCode];
  }

  // Fallbacks by department
  const defaultBranches: Record<DepartmentCode, string> = {
    KAYACHIKITSA: 'DIGESTIVE',
    SHALAKYA_TANTRA: 'EYE',
    SHALYA_TANTRA: 'WOUND_INJURY',
    PRASUTI_STRI_ROGA: 'GYNECOLOGY',
    PANCHAKARMA: 'MUSCULOSKELETAL',
    GENERAL_OPD: 'INITIAL_ASSESSMENT',
  };

  const defKey = defaultBranches[deptCode] || 'INITIAL_ASSESSMENT';
  return CONTROLLED_BRANCHES_DATA[defKey] || CONTROLLED_BRANCHES_DATA.INITIAL_ASSESSMENT;
}

export function getAllowedBranchesForDepartment(deptCode: DepartmentCode): ControlledBranchMetadata[] {
  return Object.values(CONTROLLED_BRANCHES_DATA).filter((b) => b.departmentCode === deptCode);
}


