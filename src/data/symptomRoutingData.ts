export function getDeptInfoByCode(code: DepartmentCode | string): DepartmentInfo {
  const normalized = (code || '').toUpperCase();
  const found = DEPARTMENTS_DATA.find(
    (d) => d.code === normalized || d.legacyId.toUpperCase() === normalized
  );
  return found || DEPARTMENTS_DATA[DEPARTMENTS_DATA.length - 1]; // defaults to GENERAL_OPD
}

export function getDeptInfoByLegacyId(legacyId: string): DepartmentInfo {
  const found = DEPARTMENTS_DATA.find((d) => d.legacyId === legacyId);
  return found || DEPARTMENTS_DATA[DEPARTMENTS_DATA.length - 1];
}
